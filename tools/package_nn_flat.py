def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO,
                              capture_output=True, text=True).stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def _strip_module(src: str) -> str:
    """Drop ``from __future__`` and every ``from bot`` / ``import bot`` line
    (including a parenthesized multi-line import block); keep the rest verbatim."""
    out: List[str] = []
    skip_paren = False
    for line in src.splitlines():
        if skip_paren:
            if ")" in line:
                skip_paren = False
            continue
        s = line.lstrip()
        if s.startswith("from __future__"):
            continue
        if s.startswith("from bot") or s.startswith("import bot"):
            if "(" in line and ")" not in line:
                skip_paren = True
            continue
        out.append(line)
    return "\n".join(out).strip("\n") + "\n"


def _scan_imports(path: Path) -> None:
    allowed = bundle_scan.ALLOWED_THIRD_PARTY
    tree = ast.parse(path.read_text())
    bad = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            roots = [a.name.split(".")[0] for a in node.names]
        elif isinstance(node, ast.ImportFrom):
            roots = [(node.module or "").split(".")[0]]
        else:
            continue
        for top in roots:
            if not top:
                continue
            if top in bundle_scan._STDLIB or top in allowed \
                    or top in ("helper", "lib"):
                continue
            bad.append(top)
    if bad:
        raise SystemExit(f"[package_nn_flat] disallowed imports: {sorted(set(bad))}")


def build(name: str, weights: Path, out_dir: Path) -> Path:
    weights_bytes = weights.read_bytes()
    weights_sha = hashlib.sha256(weights_bytes).hexdigest()
    literal = repr(base64.b85encode(zlib.compress(weights_bytes, 9)))

    bodies = "\n\n".join(
        f"# ===== bot/{m.relative_to(REPO / 'bot')} (spliced) =====\n"
        + _strip_module(m.read_text())
        for m in FLATTEN_MODULES[:2]  # adapters first
    )
    rest = "\n\n".join(
        f"# ===== bot/{m.relative_to(REPO / 'bot')} (spliced) =====\n"
        + _strip_module(m.read_text())
        for m in FLATTEN_MODULES[2:]  # featurizer, inference
    )
    header = HEADER.format(name=name, commit=_git_commit(), weights_sha=weights_sha[:16])
    body = (header + "\n" + bodies + ADAPTER_ALIAS + "\n" + rest
            + PIPE_LOOP.format(weights_literal=literal))

    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"{name}.py"
    out_path.write_text(body)

    # gate 1: import whitelist on the generated file
    _scan_imports(out_path)

    # gate 2: parity self-test in a clean subprocess (flat == gated bot/ path)
    proc = subprocess.run(
        [sys.executable, "-c", SELF_TEST, str(out_path), str(REPO / "tools"), str(weights)],
        cwd=REPO, capture_output=True, text=True,
    )
    if "SELFTEST_OK" not in proc.stdout:
        raise SystemExit(f"[package_nn_flat] self-test FAILED:\n{proc.stdout}\n{proc.stderr}")

    print(f"[package_nn_flat] wrote {out_path} ({out_path.stat().st_size // 1024} KB)")
    print(f"[package_nn_flat] weights sha256 {weights_sha[:16]}… | {proc.stdout.strip()}")
    print(f"[package_nn_flat] GATE before upload: "
          f"make compliance-full COMPLIANCE_BOT={out_path.relative_to(REPO)}")
    return out_path


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--name", required=True)
    ap.add_argument("--weights", type=Path, required=True,
                    help="exported actor-weights .npz (train.export / a league snap_v*.npz)")
    ap.add_argument("--out", type=Path, default=REPO / "dist")
    args = ap.parse_args()
    build(args.name, args.weights, args.out)


if __name__ == "__main__":
    main()
