#!/usr/bin/env python3
"""Flat single-file build for an NN policy (portal-safe; kit + numpy + stdlib).

Why this exists: ``tools/package_single.py`` embeds the ``bot`` package via a
``sys.modules`` trick, which the portal's import scanner rejects ("unapproved
libraries" / "No module named 'bot'"). This builder instead splices the NN's
deploy modules (``bot/adapters/obs_v1``, ``adapters/act_v1``, ``featurizer``,
``inference``) into ONE flat namespace — no ``bot`` package, no injected
imports — and inlines the exported ``weights.npz`` as a zlib+base85 literal
decoded through ``BytesIO`` at startup. numpy is on the grader's whitelist
(``tools/bundle_scan.ALLOWED_THIRD_PARTY``), so the only imports left are
stdlib, the kit (``helper``/``lib``), and numpy — exactly what passes.

Flattening details: the four modules are concatenated in dependency order; all
``from bot.*`` and ``from __future__`` lines are stripped; the engine constants
the modules read via ``spec.X`` are provided by a ``spec`` SimpleNamespace built
from ``lib.config`` (identical values to ``bot/spec.py``); and ``obs_v1`` /
``act_v1`` are aliased to this module so the few ``obs_v1.OBS_VERSION``-style
attribute references resolve to the flat names.

Build gates: (1) AST import scan on the generated file (stdlib/kit/numpy only);
(2) a subprocess self-test that runpy-loads the flat file and asserts its action
on real P4.2 scene-bank frames is **byte-identical to the gated bot/ path**
(the flatten is correct iff the outputs match). Then, before submitting:

    make compliance-full COMPLIANCE_BOT=dist/<name>.py

Usage:
    tools/package_nn_flat.py --name s2_heuristic_v1 --weights data/weights_s2.npz
"""

