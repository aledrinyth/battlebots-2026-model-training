#!/usr/bin/env python3
"""P5.5 — packager v0: repo → self-contained submission bundle.

Bundle layout (the P5.4 import bootstrap handles it natively):

    dist/<name>/
      main.py            # thin shim → bot.main.main()
      bot/               # the match-legal package, copied intact
        main.py featurizer.py inference.py safety.py spec.py adapters/…
        weights.npz      # where bot/main.py's resolver looks first

Packaging steps, each a gate:

1. **Weights validation** — the npz must load through the bot's own
   ``NumpyPolicy`` (manifest/adapter version mismatch fails here, not on the
   grader). Torch-free: ship an exported ``.npz`` (make one from a checkpoint
   with ``python -m train.export`` in the train venv).
2. **Copy** ``bot/`` (``.py`` only) + weights + shim.
3. **Whitelist scan** — the P4.3 scanner must pass on the bundle.
4. **Registry** — append provenance to ``dist/registry.json``: git commit,
   weights source + sha256, manifest, bundle bytes. A submitted bundle must
   always map back to exact code + weights.

The bundle is NOT submission-ready until ``make compliance-full
COMPLIANCE_BOT=dist/<name>/main.py`` passes (P4.4 full — printed as the next
step).

Usage:
    tools/package.py --name g1_champion --weights path/to/weights.npz [--out dist]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "tools"))

import bundle_scan  # noqa: E402  (path set above)

DEFAULT_OUT = REPO / "dist"

SHIM = '''\
"""Submission entry point — generated by tools/package.py (P5.5)."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from bot.main import main

if __name__ == "__main__":
    main()
'''


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "HEAD"], cwd=REPO,
                              capture_output=True, text=True).stdout.strip()
    except OSError:
        return "unknown"


def package(name: str, weights: Path, out_root: Path = DEFAULT_OUT) -> dict:
    """Build ``out_root/name`` from the current tree; return the registry entry."""
    from bot.inference import NumpyPolicy

    weights = weights.resolve()
    # Gate 1: the bot's own loader must accept these weights (manifest,
    # adapter versions, shapes) — fail here, never on the grader.
    policy = NumpyPolicy.load(str(weights))

    bundle = out_root / name
    if bundle.exists():
        shutil.rmtree(bundle)
    (bundle / "bot").mkdir(parents=True)

    # Gate 2: copy the match-legal package (source only — no caches, no tests).
    copied: list[str] = []
    for src in sorted((REPO / "bot").rglob("*.py")):
        rel = src.relative_to(REPO / "bot")
        dst = bundle / "bot" / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        copied.append(str(rel))
    shutil.copy2(weights, bundle / "bot" / "weights.npz")
    (bundle / "main.py").write_text(SHIM)

    # Gate 3: whitelist scan on the exact bytes being shipped.
    scan = bundle_scan.scan_bundle(bundle)
    if not scan["ok"]:
        raise SystemExit(f"bundle scan FAILED: {scan['violations']}")

    bundle_ref = (str(bundle.relative_to(REPO))
                  if bundle.resolve().is_relative_to(REPO) else str(bundle))
    entry = {
        "name": name,
        "bundle": bundle_ref,
        "git_commit": _git_commit(),
        "weights_source": str(weights),
        "weights_sha256": _sha256(weights),
        "manifest": dict(policy.manifest),
        "files": copied + ["bot/weights.npz", "main.py"],
        "bundle_bytes": sum(p.stat().st_size for p in bundle.rglob("*") if p.is_file()),
    }

    # Gate 4: provenance registry (append; newest last).
    registry_path = out_root / "registry.json"
    registry = (json.loads(registry_path.read_text())
                if registry_path.exists() else [])
    registry.append(entry)
    registry_path.write_text(json.dumps(registry, indent=2))
    return entry


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="bundle name (dist/<name>/)")
    ap.add_argument("--weights", type=Path,
                    default=REPO / "tests" / "fixtures" / "adversarial" / "weights_random.npz",
                    help="exported .npz (default: the random-init dev fixture)")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    entry = package(args.name, args.weights, args.out)
    print(f"[package] built {entry['bundle']} "
          f"({entry['bundle_bytes']:,} bytes, {len(entry['files'])} files)")
    print(f"[package] weights {entry['weights_sha256'][:12]}… from {entry['weights_source']}")
    print(f"[package] registry: {args.out / 'registry.json'} ({entry['git_commit'][:9]})")
    print("[package] NOT submission-ready until this passes:")
    print(f"          make compliance-full COMPLIANCE_BOT={entry['bundle']}/main.py")


if __name__ == "__main__":
    main()
