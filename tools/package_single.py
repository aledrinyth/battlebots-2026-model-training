#!/usr/bin/env python3
"""P5.5b — single-file submission build (portal accepts exactly one ``.py``).

Amalgamates the match-legal ``bot/`` package and the exported weights into
ONE self-contained Python file:

* **Source embedding, zero rewriting.** Every ``bot`` module's source is
  embedded as a string literal; at startup the file creates real module
  objects, registers them in ``sys.modules`` under their true names
  (``bot``, ``bot.spec``, ``bot.adapters.act_v1``, …), and executes each
  source in dependency order. All the package's own ``from bot.x import y``
  statements then resolve through ``sys.modules`` untouched — the shipped
  code is byte-identical to the gated ``bot/`` tree.
* **Weight embedding.** The ``weights.npz`` bytes are zlib-compressed and
  base85-encoded into a literal; at startup they are decoded into
  ``bot.main.WEIGHTS_BYTES`` and loaded via ``BytesIO`` — no filesystem
  access, no temp files (sandbox-friendly).

Build gates, in order: weights load through ``NumpyPolicy`` (schema check);
the P4.3 whitelist scan on the *source* ``bot/`` tree; generation; a
**self-test in a clean subprocess** (install the embedded modules, decode
the weights, featurize a real P4.2 scene-bank frame, run the forward pass);
registry entry. The file is NOT submission-ready until it passes the full
pipe-runner gate — the builder prints the command:

    make compliance-full COMPLIANCE_BOT=dist/<name>.py

Usage:
    tools/package_single.py --name s1_champion --weights data/weights_s1_champion.npz
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import subprocess
import sys
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "tools"))

import bundle_scan  # noqa: E402  (path set above)

#: Execution order = dependency order (imports resolve at exec time; a module
#: must be executed before anything that ``from``-imports its names).
MODULE_ORDER = [
    ("bot", "bot/__init__.py"),
    ("bot.spec", "bot/spec.py"),
    ("bot.adapters", "bot/adapters/__init__.py"),
    ("bot.adapters.obs_v1", "bot/adapters/obs_v1.py"),
    ("bot.adapters.act_v1", "bot/adapters/act_v1.py"),
    ("bot.featurizer", "bot/featurizer.py"),
    ("bot.inference", "bot/inference.py"),
    ("bot.safety", "bot/safety.py"),
    ("bot.main", "bot/main.py"),
]

PACKAGES = {"bot", "bot.adapters"}

TEMPLATE = '''\
"""{name} — single-file agar.io submission (auto-generated; do not edit).

Generated by tools/package_single.py from the gated bot/ tree at commit
{commit} with weights sha256 {weights_sha}. The embedded module sources are
byte-identical to that tree; the embedded weights decode to the exact
exported .npz. Regenerate rather than editing.
"""

import base64
import sys
import types
import zlib

_ORDER = {order!r}
_PACKAGES = {packages!r}

_SOURCES = {sources}

_WEIGHTS_Z85 = (
{weights_literal}
)


def _install_modules() -> None:
    for name in _ORDER:  # register everything first, then execute in order
        mod = types.ModuleType(name)
        mod.__file__ = "<embedded {{}}>".format(name)
        if name in _PACKAGES:
            mod.__path__ = []
        sys.modules[name] = mod
    for name in _ORDER:
        code = compile(_SOURCES[name], "<embedded {{}}>".format(name), "exec")
        exec(code, sys.modules[name].__dict__)
        parent, _, child = name.rpartition(".")
        if parent:
            setattr(sys.modules[parent], child, sys.modules[name])


def _decode_weights() -> bytes:
    return zlib.decompress(base64.b85decode(_WEIGHTS_Z85))


if __name__ == "__main__":
    _install_modules()
    bot_main = sys.modules["bot.main"]
    bot_main.WEIGHTS_BYTES = _decode_weights()
    bot_main.main()
'''

SELF_TEST = """
import io, sys
import runpy

path = sys.argv[1]
ns = runpy.run_path(path, run_name="_selftest")  # __main__ guard stays cold
ns["_install_modules"]()
blob = ns["_decode_weights"]()

from bot.inference import NumpyPolicy          # resolves via embedded modules
from bot.featurizer import Featurizer
from bot.adapters.act_v1 import ActionAdapter
from lib.interface.queries.query_move import QueryMovePlayer

policy = NumpyPolicy.load(io.BytesIO(blob))
sys.path.insert(0, sys.argv[3])
import scene_bank
bank = scene_bank.load_bank()
scene = next(s for s in bank["scenes"] if s["name"] == "max_entities")
feat, hidden = Featurizer(), policy.initial_hidden()
for raw in scene["frames"]:
    q = QueryMovePlayer.model_validate_json(raw)
    action, hidden = policy.act(feat.featurize(q), hidden)
    move = ActionAdapter.to_move(q.you.player_id, action)
    assert move.model_dump_json()
print("SELFTEST_OK", len(blob))
"""


def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO,
                              capture_output=True, text=True).stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def build_single(name: str, weights: Path, out_dir: Path) -> dict:
    """Generate ``out_dir/<name>.py``; return the registry entry."""
    from bot.inference import NumpyPolicy

    weights = weights.resolve()
    policy = NumpyPolicy.load(str(weights))  # gate 1: schema/manifest sanity

    scan = bundle_scan.scan_bundle(REPO / "bot")  # gate 2: whitelist on the source tree
    if not scan["ok"]:
        raise SystemExit(f"bot/ whitelist scan FAILED: {scan['violations']}")

    sources: dict[str, str] = {}
    for mod_name, rel in MODULE_ORDER:
        sources[mod_name] = (REPO / rel).read_text()

    raw = weights.read_bytes()
    weights_sha = hashlib.sha256(raw).hexdigest()
    encoded = base64.b85encode(zlib.compress(raw, level=9)).decode()
    # Wrap the b85 literal at 100 chars so the file stays editor/portal-friendly.
    chunks = [f'    "{encoded[i:i + 100]}"' for i in range(0, len(encoded), 100)]

    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"{name}.py"
    out_path.write_text(TEMPLATE.format(
        name=name,
        commit=_git_commit(),
        weights_sha=weights_sha[:16],
        order=[m for m, _ in MODULE_ORDER],
        packages=sorted(PACKAGES),
        sources="{\n" + ",\n".join(
            f"    {m!r}: {sources[m]!r}" for m, _ in MODULE_ORDER) + "\n}",
        weights_literal="\n".join(chunks),
    ))

    # Gate 3: self-test in a CLEAN subprocess (no repo bot/ on the path shadowing
    # the embedded modules would defeat the point — run from the output dir).
    st = subprocess.run(
        [sys.executable, "-c", SELF_TEST, str(out_path), "-", str(REPO / "tools")],
        capture_output=True, text=True, cwd=out_dir,
    )
    if "SELFTEST_OK" not in st.stdout:
        raise SystemExit(f"single-file self-test FAILED:\n{st.stdout}\n{st.stderr}")

    entry = {
        "name": name,
        "kind": "single-file",
        "file": str(out_path.relative_to(REPO) if out_path.resolve().is_relative_to(REPO)
                    else out_path),
        "git_commit": _git_commit(),
        "weights_source": str(weights),
        "weights_sha256": weights_sha,
        "manifest": dict(policy.manifest),
        "file_bytes": out_path.stat().st_size,
    }
    registry_path = out_dir / "registry.json"
    registry = json.loads(registry_path.read_text()) if registry_path.exists() else []
    registry.append(entry)
    registry_path.write_text(json.dumps(registry, indent=2))
    return entry


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True)
    ap.add_argument("--weights", type=Path, required=True,
                    help="exported .npz (python -m train.export from a checkpoint)")
    ap.add_argument("--out", type=Path, default=REPO / "dist")
    args = ap.parse_args()

    entry = build_single(args.name, args.weights, args.out)
    print(f"[single] built {entry['file']} ({entry['file_bytes']:,} bytes) "
          f"— weights {entry['weights_sha256'][:12]}… @ {entry['git_commit']}")
    print("[single] self-test passed (embedded modules + weights + scene-bank frame).")
    print("[single] NOT submission-ready until this passes:")
    print(f"         make compliance-full COMPLIANCE_BOT={entry['file']}")


if __name__ == "__main__":
    main()
