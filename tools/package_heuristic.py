    SPLIT_REACH=SPLIT_EJECT_SPEED / (1.0 - SPLIT_EJECT_DRAG),
    VIRUS_POP_MASS_THRESHOLD=VIRUS_SIZE * VIRUS_SIZE * EAT_SIZE_RATIO,
