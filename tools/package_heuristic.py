def _git_commit() -> str:
    try:
        return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=REPO,
                              capture_output=True, text=True).stdout.strip() or "unknown"
    except OSError:
        return "unknown"


def _extract_body(src: str) -> str:
    idx = src.index(BODY_MARKER)
    return src[idx:].rstrip() + "\n"


def _scan_imports(path: Path) -> None:
    """The real 'unapproved libraries' gate: every top-level import in the
    generated file must be stdlib, whitelisted third-party, or the kit
    (helper/lib)."""
    tree = ast.parse(path.read_text())
    allowed = (bundle_scan._STDLIB | bundle_scan.ALLOWED_THIRD_PARTY
               | {"helper", "lib"})
    bad = sorted(t for t in bundle_scan._top_level_imports(tree) if t not in allowed)
    if bad:
        raise SystemExit(f"generated file imports non-approved packages: {bad}")


def build_flat(name: str, out_dir: Path) -> dict:
    body = _extract_body(HEURISTIC_SRC.read_text())
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"{name}.py"
    out_path.write_text(
        HEADER.format(name=name, commit=_git_commit(), body=body) + PIPE_LOOP
    )

    _scan_imports(out_path)  # gate 1: no unapproved libraries in the artifact

    # gate 2: self-test in a clean subprocess, from the output dir
    st = subprocess.run(
        [sys.executable, "-c", SELF_TEST, str(out_path), str(REPO / "tools")],
        capture_output=True, text=True, cwd=out_dir,
    )
    if "SELFTEST_OK" not in st.stdout:
        raise SystemExit(f"single-file self-test FAILED:\n{st.stdout}\n{st.stderr}")

    entry = {
        "name": name,
        "kind": "single-file-heuristic-flat",
        "file": str(out_path.relative_to(REPO)
                    if out_path.resolve().is_relative_to(REPO) else out_path),
        "git_commit": _git_commit(),
        "file_bytes": out_path.stat().st_size,
    }
    registry_path = out_dir / "registry.json"
    registry = json.loads(registry_path.read_text()) if registry_path.exists() else []
    registry.append(entry)
    registry_path.write_text(json.dumps(registry, indent=2))
    return entry


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True)
    ap.add_argument("--out", type=Path, default=REPO / "dist")
    args = ap.parse_args()

    entry = build_flat(args.name, args.out)
    print(f"[heuristic] built {entry['file']} ({entry['file_bytes']:,} bytes) "
          f"@ {entry['git_commit']}")
    print("[heuristic] import scan + self-test passed (kit + stdlib only, "
          "scene-bank frame).")
    print("[heuristic] NOT submission-ready until this passes:")
    print(f"            make compliance-full COMPLIANCE_BOT={entry['file']}")


if __name__ == "__main__":
    main()
